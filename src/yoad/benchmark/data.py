"""Dataset interface and the deterministic synthetic generator.

A DatasetBundle keeps features, labels, group (participant) identifiers, visit dates, feature metadata and task-specific
information separate. Stage 1 registers only the synthetic adapter; a future approved ADNI/NACC adapter must implement
`DatasetAdapter` and is out of scope here (no real-data reader exists in this package).
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Callable

import numpy as np
import pandas as pd

GENERATOR_VERSION = "synthetic-v1"
SYNTHETIC_PROVENANCE = ("Generated by src.benchmark.data.generate_synthetic; entirely synthetic; no value, identifier, "
                        "cohort size or distribution is taken from ADNI, NACC or any real participant.")


class GovernanceError(RuntimeError):
    """Raised when data that is not explicitly synthetic would enter the Stage 1 benchmark."""


@dataclass
class FeatureInfo:
    name: str
    group: str          # hypothetical modality, e.g. "demographic", "cognitive", "imaging"
    kind: str           # "numeric" | "categorical"


@dataclass
class DatasetBundle:
    X: pd.DataFrame                     # one row per observation (visit)
    y: pd.Series                        # binary labels aligned with X
    groups: pd.Series                   # participant identifiers aligned with X
    features: list[FeatureInfo]
    synthetic: bool
    provenance: str
    visit_dates: pd.Series | None = None
    task_info: dict = field(default_factory=dict)   # e.g. synthetic event times for future survival interfaces

    def __post_init__(self):
        n = len(self.X)
        if not (len(self.y) == n and len(self.groups) == n and (self.visit_dates is None or len(self.visit_dates) == n)):
            raise ValueError("X, y, groups and visit_dates must have the same length")
        names = [f.name for f in self.features]
        if sorted(names) != sorted(self.X.columns):
            raise ValueError("feature metadata must describe exactly the columns of X")
        bad = {f.kind for f in self.features} - {"numeric", "categorical"}
        if bad:
            raise ValueError(f"unknown feature kinds: {bad}")

    def feature_groups(self) -> list[str]:
        return sorted({f.group for f in self.features})

    def select_groups(self, groups: list[str]) -> "DatasetBundle":
        """Early-fusion view: keep only the features of the requested groups."""
        unknown = set(groups) - set(self.feature_groups())
        if unknown:
            raise ValueError(f"unknown feature groups {sorted(unknown)}; available {self.feature_groups()}")
        keep = [f for f in self.features if f.group in groups]
        return DatasetBundle(self.X[[f.name for f in keep]], self.y, self.groups, keep, self.synthetic, self.provenance,
                             self.visit_dates, self.task_info)


# ------------------------------------------------------------------------------------------------ adapter registry
@dataclass(frozen=True)
class DatasetAdapter:
    name: str
    synthetic: bool
    allowed_params: frozenset
    feature_groups: tuple
    load: Callable[..., DatasetBundle]


SYN_GROUPS = ("cognitive", "demographic", "imaging")


def _check_rate(name, v, lo=0.0, hi=1.0, open_hi=True):
    if not isinstance(v, (int, float)) or v < lo or (v >= hi if open_hi else v > hi):
        raise ValueError(f"{name} must be in [{lo}, {hi}{')' if open_hi else ']'}; got {v!r}")


def generate_synthetic(n_participants: int = 300, visits_per_participant=(1, 4), positive_fraction: float = 0.3,
                       missing_rate: float = 0.1, n_imaging: int = 6, seed: int = 0) -> DatasetBundle:
    """Deterministic synthetic visit-level data with a known signal.

    True model (participant level): logit P(y=1) = b0 + 1.2*cog_1 - 0.8*img_1 + 0.5*age_z, with b0 chosen so the mean
    risk equals `positive_fraction`. Other features are noise. Each participant has 1..k visits; visit features are the
    participant's latent values plus small visit noise; the label is constant within a participant. Missing values are
    MCAR at `missing_rate` over feature cells only.
    """
    if not isinstance(n_participants, int) or n_participants < 10:
        raise ValueError("n_participants must be an integer >= 10")
    lo, hi = visits_per_participant
    if not (isinstance(lo, int) and isinstance(hi, int) and 1 <= lo <= hi):
        raise ValueError("visits_per_participant must be (lo, hi) integers with 1 <= lo <= hi")
    _check_rate("positive_fraction", positive_fraction, 0.01, 0.99)
    _check_rate("missing_rate", missing_rate, 0.0, 0.9)
    if not isinstance(n_imaging, int) or n_imaging < 1:
        raise ValueError("n_imaging must be an integer >= 1")
    rng = np.random.default_rng(seed)
    n = n_participants
    age_z = rng.normal(size=n)
    cog = rng.normal(size=(n, 3))
    img = rng.normal(size=(n, n_imaging))
    sex = rng.choice(["F", "M"], size=n)
    site = rng.choice(["s1", "s2", "s3"], size=n, p=[0.5, 0.3, 0.2])
    lin = 1.2 * cog[:, 0] - 0.8 * img[:, 0] + 0.5 * age_z
    a, b = -20.0, 20.0                              # bisection for the intercept giving the requested prevalence
    for _ in range(100):
        m = (a + b) / 2
        if (1 / (1 + np.exp(-(m + lin)))).mean() < positive_fraction:
            a = m
        else:
            b = m
    p = 1 / (1 + np.exp(-((a + b) / 2 + lin)))
    y_part = (rng.random(n) < p).astype(int)
    n_vis = rng.integers(lo, hi + 1, size=n)
    rows, ids, ys, dates = [], [], [], []
    start = pd.Timestamp("2000-01-01") + pd.to_timedelta(rng.integers(0, 3650, size=n), unit="D")
    for i in range(n):
        for v in range(n_vis[i]):
            noise = rng.normal(scale=0.2, size=3 + n_imaging + 1)
            rows.append([60 + 8 * (age_z[i] + noise[0] * 0.1) + v * 0.5, sex[i], site[i],
                         *(cog[i] + noise[1:4] * 0.5), *(img[i] + noise[4:4 + n_imaging] * 0.5)][:3 + 3 + n_imaging])
            ids.append(f"SYN-{i:05d}")
            ys.append(y_part[i])
            dates.append(start[i] + pd.DateOffset(months=6 * v))
    cols = (["syn_age", "syn_sex", "syn_site"] + [f"syn_cog_{j + 1}" for j in range(3)]
            + [f"syn_img_{j + 1}" for j in range(n_imaging)])
    X = pd.DataFrame(rows, columns=cols)
    if missing_rate > 0:
        mask = rng.random(X.shape) < missing_rate
        X = X.mask(mask)
    feats = ([FeatureInfo("syn_age", "demographic", "numeric"), FeatureInfo("syn_sex", "demographic", "categorical"),
              FeatureInfo("syn_site", "demographic", "categorical")]
             + [FeatureInfo(f"syn_cog_{j + 1}", "cognitive", "numeric") for j in range(3)]
             + [FeatureInfo(f"syn_img_{j + 1}", "imaging", "numeric") for j in range(n_imaging)])
    event_month = np.where(y_part == 1, rng.uniform(1, 24, size=n), np.nan)
    return DatasetBundle(X=X, y=pd.Series(ys, name="y", dtype=int), groups=pd.Series(ids, name="group"), features=feats,
                         synthetic=True, provenance=f"{GENERATOR_VERSION}: {SYNTHETIC_PROVENANCE}",
                         visit_dates=pd.Series(dates, name="visit_date"),
                         task_info={"synthetic_event_month_by_participant": dict(zip([f"SYN-{i:05d}" for i in range(n)], event_month)),
                                    "true_signal_features": ["syn_cog_1", "syn_img_1", "syn_age"]})


def _load_synthetic(**params) -> DatasetBundle:
    if "visits_per_participant" in params:
        params["visits_per_participant"] = tuple(params["visits_per_participant"])
    return generate_synthetic(**params)


ADAPTERS: dict[str, DatasetAdapter] = {
    "synthetic": DatasetAdapter("synthetic", True,
                                frozenset({"n_participants", "visits_per_participant", "positive_fraction", "missing_rate",
                                           "n_imaging", "seed"}), SYN_GROUPS, _load_synthetic),
}


def load_dataset(adapter: str, params: dict) -> DatasetBundle:
    if adapter not in ADAPTERS:
        raise ValueError(f"unknown dataset adapter {adapter!r}; registered: {sorted(ADAPTERS)}")
    ad = ADAPTERS[adapter]
    bundle = ad.load(**dict(params))
    if not (ad.synthetic and bundle.synthetic):
        raise GovernanceError("Stage 1 accepts only synthetic data; no approved real-data adapter exists")
    return bundle
